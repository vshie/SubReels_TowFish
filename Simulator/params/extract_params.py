#!/usr/bin/env python3
"""Write the towfish's as-flown parameters from the 4 Nov log as a SITL defaults file.

Keeps everything that shapes control (ATC_*, PSC_*, PILOT_*, MOT_*, SERVO*,
RC*, EK3_*, AHRS_TRIM_*, ...). Drops what only describes the physical board
(sensor device IDs and calibrations, serial ports, CAN, LEDs, leak pins,
runtime statistics). sitl_overrides.parm is layered on top of this.

Usage: python3 params/extract_params.py   (writes params/towfish_as_flown.parm)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from towsim.logs import load_fish  # noqa: E402

DROP = [
    r"^STAT_", r"^FORMAT_VERSION$", r"^SYSID_SW_", r"_DEVID", r"_DEV_ID",
    r"^INS_(ACC|GYR)\d?_?(ID|CALTEMP)", r"^INS_ACC\d?(OFFS|SCAL)_", r"^INS_GYR\d?OFFS_",
    r"^INS_TCAL", r"^INS_ACC_ID$", r"^INS_GYR_ID$", r"^INS_ACC\d_ID$", r"^INS_GYR\d_ID$",
    r"^COMPASS_(OFS|DIA|ODI|MOT|SCALE|ORIENT|PRIO|EXTERN)", r"^COMPASS_DEV_ID",
    r"^BARO\d?_GND_PRESS", r"^BARO_EXT_BUS", r"^BARO_PROBE_EXT",
    r"^SERIAL\d", r"^GPS", r"^CAN_", r"^BRD_", r"^NTF_", r"^LEAK\d", r"^NET_",
    r"^BATT", r"^TEMP\d?_", r"^RELAY", r"^SCR_", r"^LOG_BACKEND_TYPE$",
    # AHRS_ORIGIN_* stays: without an EKF origin ArduSub reports VFR_HUD.alt
    # as 0, and the extension reads the fish's depth from VFR_HUD.
    r"^AHRS_ORIENTATION$", r"^SIM_",
]


def main() -> int:
    fish = load_fish()
    p = fish["PARM"]
    values: dict[str, float] = {}
    for name, value in zip(p["Name"], p["Value"]):
        values.setdefault(name, value)  # value at log start
    kept = {k: v for k, v in values.items()
            if not any(re.search(rx, k) for rx in DROP)}
    out = HERE / "towfish_as_flown.parm"
    with out.open("w") as f:
        f.write("# As-flown towfish parameters, towfish_00000103.BIN (4 Nov 2026).\n")
        f.write("# Generated by params/extract_params.py -- do not hand-edit;\n")
        f.write("# put SITL-only changes in sitl_overrides.parm.\n")
        for k in sorted(kept):
            f.write(f"{k},{kept[k]:.9g}\n")
    print(f"wrote {out} ({len(kept)} kept, {len(values) - len(kept)} dropped)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
